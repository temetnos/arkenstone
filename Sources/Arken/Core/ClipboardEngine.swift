public enum ClipboardContentType: String, CaseIterable, Identifiable {
    case all = "all"
    case text = "text"
    case image = "image"
    case code = "code"
    case url = "url"
    case color = "color"
    
    public var id: String { rawValue }
    
    public var title: String {
        switch self {
        case .all: return L10n.tr("All", "Tümü")
        case .text: return L10n.tr("Text", "Metin")
        case .image: return L10n.tr("Image", "Görsel")
        case .code: return L10n.tr("Code", "Kod")
        case .url: return L10n.tr("Link", "Bağlantı")
        case .color: return L10n.tr("Color", "Renk")
        }
    }
    
    public var icon: String {
        switch self {
        case .all: return "square.grid.2x2"
        case .text: return "text.quote"
        case .image: return "photo.fill"
        case .code: return "curlybraces"
        case .url: return "link"
        case .color: return "paintpalette"
        }
    }
}

public struct ClipboardItem: Identifiable, Equatable {
    public let id: UUID
    public let content: String
    public let preview: String
    public let type: ClipboardContentType
    public let copiedAt: Date
    public let characterCount: Int
    public var isPinned: Bool
    public let imageData: Data?
    public let imageDimensions: CGSize?
    public let byteSizeFormatted: String?
    
    // Text item initializer
    public init(content: String, isPinned: Bool = false) {
        self.id = UUID()
        self.content = content
        self.copiedAt = Date()
        self.characterCount = content.count
        self.isPinned = isPinned
        self.imageData = nil
        self.imageDimensions = nil
        self.byteSizeFormatted = nil
        
        let trimmed = content.trimmingCharacters(in: .whitespacesAndNewlines)
        
        // Detect Type
        if trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://") || (trimmed.contains(".com") && !trimmed.contains(" ")) {
            self.type = .url
        } else if (trimmed.hasPrefix("#") && (trimmed.count == 7 || trimmed.count == 4)) || trimmed.hasPrefix("rgb(") {
            self.type = .color
        } else if trimmed.contains("func ") || trimmed.contains("const ") || trimmed.contains("var ") || trimmed.contains("import ") || trimmed.contains("{") || trimmed.contains("def ") || trimmed.contains("class ") {
            self.type = .code
        } else {
            self.type = .text
        }
        
        // Single-line preview
        let clean = content.replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
        self.preview = clean.count > 120 ? String(clean.prefix(120)) + "..." : clean
    }
    
    // Image item initializer
    public init(imageData: Data, dimensions: CGSize, sourceName: String? = nil, isPinned: Bool = false) {
        self.id = UUID()
        self.type = .image
        self.copiedAt = Date()
        self.isPinned = isPinned
        self.imageData = imageData
        self.imageDimensions = dimensions
        self.characterCount = imageData.count
        
        let kb = Double(imageData.count) / 1024.0
        let sizeStr = kb > 1024.0 ? String(format: "%.1f MB", kb / 1024.0) : String(format: "%.0f KB", kb)
        self.byteSizeFormatted = sizeStr
        
        let defaultName = LocalizationManager.shared.language == .tr ? "Kopyalanan Görsel" : "Copied Image"
        let name = sourceName ?? defaultName
        self.content = "\(name) (\(Int(dimensions.width)) × \(Int(dimensions.height)) • \(sizeStr))"
        self.preview = "\(name) • \(Int(dimensions.width)) × \(Int(dimensions.height)) • \(sizeStr)"
    }
    
    public static func == (lhs: ClipboardItem, rhs: ClipboardItem) -> Bool {
        return lhs.id == rhs.id && lhs.isPinned == rhs.isPinned && lhs.content == rhs.content && lhs.type == rhs.type
    }
}

public class ClipboardEngine: ObservableObject {
    public static let shared = ClipboardEngine()
    
    @Published public var items: [ClipboardItem] = []
    @Published public var searchQuery: String = ""
    @Published public var selectedFilter: ClipboardContentType = .all
    
    private var lastChangeCount: Int = 0
    private var pollTimer: Timer?
    private let maxItems = 40
    
    // Privacy & Security: Standard Concealed/Sensitive types used by 1Password, Bitwarden, Apple Keychain, KeePass etc.
    private static let sensitivePasteboardTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.source"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.sophias-world.clipboard-ignore"),
        NSPasteboard.PasteboardType("net.antelle.keeweb"),
        NSPasteboard.PasteboardType("com.bitwarden.desktop"),
        NSPasteboard.PasteboardType("org.keepassxc.keepassxc"),
        NSPasteboard.PasteboardType("com.apple.findmy.security")
    ]
    
    public init() {
        self.lastChangeCount = NSPasteboard.general.changeCount
        checkPasteboard()
        startPolling()
    }
    
    deinit {
        pollTimer?.invalidate()
    }
    
    public func startPolling() {
        pollTimer?.invalidate()
        let timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.pollTimer = timer
    }
    
    public func checkPasteboard() {
        let pboard = NSPasteboard.general
        guard pboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pboard.changeCount
        
        // 1. PRIVACY & SECURITY: Ignore passwords & concealed data from password managers
        if let types = pboard.types, types.contains(where: { Self.sensitivePasteboardTypes.contains($0) }) {
            return
        }
        
        // 2. CHECK FOR COPIED IMAGES (Screenshots, Browser Images, Finder Images)
        if let imageResult = extractImageFromPasteboard(pboard) {
            handleNewImage(data: imageResult.data, size: imageResult.size, name: imageResult.name)
            return
        }
        
        // 3. CHECK FOR TEXT
        guard let text = pboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return
        }
        
        // Memory guard for massive text payloads (> 100,000 characters)
        let processedText: String
        if text.count > 100_000 {
            processedText = String(text.prefix(100_000)) + "\n\n... [Content truncated at 100,000 characters for RAM protection]"
        } else {
            processedText = text
        }
        
        // Avoid adding if same as the very latest item
        if let first = items.first, first.type != .image, first.content == processedText {
            return
        }
        
        // If it already exists in the list, remove it from old position and bump to top
        items.removeAll(where: { $0.type != .image && $0.content == processedText && !$0.isPinned })
        
        let newItem = ClipboardItem(content: processedText)
        let firstUnpinnedIndex = items.firstIndex(where: { !$0.isPinned }) ?? items.count
        items.insert(newItem, at: firstUnpinnedIndex)
        
        trimHistory()
    }
    
    private func extractImageFromPasteboard(_ pboard: NSPasteboard) -> (data: Data, size: CGSize, name: String?)? {
        let types = pboard.types ?? []
        
        var rawData: Data? = nil
        var sourceName: String? = nil
        
        if types.contains(.png), let png = pboard.data(forType: .png) {
            rawData = png
        } else if types.contains(.tiff), let tiff = pboard.data(forType: .tiff) {
            if let rep = NSBitmapImageRep(data: tiff),
               let png = rep.representation(using: .png, properties: [:]) {
                rawData = png
            } else {
                rawData = tiff
            }
        } else if let fileURLs = pboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
                  let first = fileURLs.first,
                  ["png", "jpg", "jpeg", "gif", "webp", "heic", "tiff", "bmp"].contains(first.pathExtension.lowercased()) {
            if let fileData = try? Data(contentsOf: first) {
                rawData = fileData
                sourceName = first.lastPathComponent
            }
        }
        
        guard let data = rawData, let image = NSImage(data: data), image.isValid else {
            return nil
        }
        
        var pixelWidth = Int(image.size.width)
        var pixelHeight = Int(image.size.height)
        if let rep = image.representations.first {
            if rep.pixelsWide > 0 && rep.pixelsHigh > 0 {
                pixelWidth = rep.pixelsWide
                pixelHeight = rep.pixelsHigh
            }
        }
        
        // Memory optimization: if image is larger than 1600px, downsample and compress to prevent RAM bloat
        var finalData = data
        let maxDim = max(pixelWidth, pixelHeight)
        if maxDim > 1600 {
            let scale = 1600.0 / Double(maxDim)
            let newSize = NSSize(width: Double(pixelWidth) * scale, height: Double(pixelHeight) * scale)
            let resized = NSImage(size: newSize)
            resized.lockFocus()
            image.draw(in: NSRect(origin: .zero, size: newSize))
            resized.unlockFocus()
            if let tiff = resized.tiffRepresentation,
               let rep = NSBitmapImageRep(data: tiff),
               let comp = rep.representation(using: .jpeg, properties: [.compressionFactor: 0.82]) {
                finalData = comp
                pixelWidth = Int(newSize.width)
                pixelHeight = Int(newSize.height)
            }
        } else if data.count > 800 * 1024,
                  let rep = NSBitmapImageRep(data: data),
                  let comp = rep.representation(using: .jpeg, properties: [.compressionFactor: 0.85]) {
            finalData = comp
        }
        
        return (finalData, CGSize(width: pixelWidth, height: pixelHeight), sourceName)
    }
    
    private func handleNewImage(data: Data, size: CGSize, name: String?) {
        // Check if latest item is already this identical image
        if let first = items.first, first.type == .image, first.imageData?.count == data.count && first.imageDimensions == size {
            return
        }
        
        // Remove if duplicate existing in list
        items.removeAll(where: { $0.type == .image && $0.imageData?.count == data.count && $0.imageDimensions == size && !$0.isPinned })
        
        let newItem = ClipboardItem(imageData: data, dimensions: size, sourceName: name)
        let firstUnpinnedIndex = items.firstIndex(where: { !$0.isPinned }) ?? items.count
        items.insert(newItem, at: firstUnpinnedIndex)
        
        trimHistory()
    }
    
    private let maxMemoryBytes: Int = 30 * 1024 * 1024 // 30 MB ceiling
    
    private func trimHistory() {
        // 1. Trim item count to maxItems
        while items.count > maxItems {
            if let lastUnpinned = items.lastIndex(where: { !$0.isPinned }) {
                items.remove(at: lastUnpinned)
            } else {
                break
            }
        }
        
        // 2. Enforce strict RAM ceiling for stored image data (< 30 MB)
        var totalImageBytes = items.compactMap { $0.imageData?.count }.reduce(0, +)
        while totalImageBytes > maxMemoryBytes {
            if let lastUnpinnedImage = items.lastIndex(where: { $0.type == .image && !$0.isPinned }) {
                let removedBytes = items[lastUnpinnedImage].imageData?.count ?? 0
                items.remove(at: lastUnpinnedImage)
                totalImageBytes -= removedBytes
            } else {
                break
            }
        }
    }
    
    public func copyToSystem(item: ClipboardItem) {
        let pboard = NSPasteboard.general
        pboard.clearContents()
        
        if item.type == .image, let data = item.imageData, let img = NSImage(data: data) {
            pboard.writeObjects([img])
            pboard.setData(data, forType: .png)
            self.lastChangeCount = pboard.changeCount
            SoundManager.shared.play(.success)
        } else {
            pboard.setString(item.content, forType: .string)
            self.lastChangeCount = pboard.changeCount
            SoundManager.shared.play(.action)
        }
    }
    
    public func sendImageToShelf(item: ClipboardItem) {
        guard item.type == .image, let data = item.imageData else { return }
        
        let fileName = "Arken_Clipboard_\(Int(Date().timeIntervalSince1970)).png"
        let tempURL = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent(fileName)
        
        do {
            try data.write(to: tempURL)
            DropShelfEngine.shared.addURLs([tempURL])
            SoundManager.shared.play(.pop)
        } catch {
            print("Failed to save image to shelf: \(error)")
        }
    }
    
    public func togglePin(id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        
        objectWillChange.send()
        items[idx].isPinned.toggle()
        
        var updated = items
        updated.sort { item1, item2 in
            if item1.isPinned == item2.isPinned {
                return item1.copiedAt > item2.copiedAt
            }
            return item1.isPinned && !item2.isPinned
        }
        self.items = updated
        
        SoundManager.shared.play(.pop)
    }
    
    public func deleteItem(id: UUID) {
        items.removeAll(where: { $0.id == id })
    }
    
    public func clearUnpinned() {
        items.removeAll(where: { !$0.isPinned })
    }
    
    public func clearAll() {
        items.removeAll()
    }
    
    public var filteredItems: [ClipboardItem] {
        items.filter { item in
            let matchesFilter = (selectedFilter == .all) || (item.type == selectedFilter)
            let matchesSearch = searchQuery.isEmpty || item.content.localizedCaseInsensitiveContains(searchQuery)
            return matchesFilter && matchesSearch
        }
    }
    
    public func transformAndCopy(item: ClipboardItem, transform: TextTransform) {
        let text = item.content
        let transformed: String
        switch transform {
        case .stripFormatting:
            transformed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        case .formatJSON:
            if let data = text.data(using: .utf8),
               let json = try? JSONSerialization.jsonObject(with: data, options: []),
               let prettyData = try? JSONSerialization.data(withJSONObject: json, options: [.prettyPrinted, .sortedKeys]),
               let prettyString = String(data: prettyData, encoding: .utf8) {
                transformed = prettyString
            } else {
                transformed = text
            }
        case .minifyJSON:
            if let data = text.data(using: .utf8),
               let json = try? JSONSerialization.jsonObject(with: data, options: []),
               let minData = try? JSONSerialization.data(withJSONObject: json, options: []),
               let minString = String(data: minData, encoding: .utf8) {
                transformed = minString
            } else {
                transformed = text
            }
        case .base64Encode:
            transformed = Data(text.utf8).base64EncodedString()
        case .base64Decode:
            if let data = Data(base64Encoded: text.trimmingCharacters(in: .whitespacesAndNewlines)),
               let decoded = String(data: data, encoding: .utf8) {
                transformed = decoded
            } else {
                transformed = text
            }
        case .urlEncode:
            transformed = text.addingPercentEncoding(withAllowedCharacters: .urlQueryAllowed) ?? text
        case .urlDecode:
            transformed = text.removingPercentEncoding ?? text
        case .uppercase:
            transformed = text.uppercased()
        case .lowercase:
            transformed = text.lowercased()
        }
        
        let pboard = NSPasteboard.general
        pboard.clearContents()
        pboard.setString(transformed, forType: .string)
        SoundManager.shared.play(.pop)
    }
}

public enum TextTransform: String, CaseIterable, Identifiable {
    case stripFormatting = "Plain Text"
    case formatJSON = "JSON Pretty"
    case minifyJSON = "JSON Minify"
    case base64Encode = "Base64 Encode"
    case base64Decode = "Base64 Decode"
    case urlEncode = "URL Encode"
    case urlDecode = "URL Decode"
    case uppercase = "UPPERCASE"
    case lowercase = "lowercase"
    
    public var id: String { rawValue }
    
    public var title: String {
        switch self {
        case .stripFormatting: return L10n.tr("Plain Text (Trim)", "Düz Metin (Kırp)")
        case .formatJSON: return L10n.tr("Format JSON (Pretty)", "JSON Hizala (Pretty)")
        case .minifyJSON: return L10n.tr("Minify JSON", "JSON Sıkıştır (Minify)")
        case .base64Encode: return "Base64 Encode"
        case .base64Decode: return "Base64 Decode"
        case .urlEncode: return "URL Encode"
        case .urlDecode: return "URL Decode"
        case .uppercase: return L10n.tr("UPPERCASE", "BÜYÜK HARF")
        case .lowercase: return L10n.tr("lowercase", "küçük harf")
        }
    }
}
